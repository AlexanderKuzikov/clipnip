// сам. Поэтому есть облегчённая сборка (см. deno_embed_slim.go): exe тоньше
// на 42 МБ и с одним встроенным PE меньше — а меньше вложенных исполняемых
// файлов, тем слабее сигнатура «дроппера» для эвристик антивирусов.
const denoGz = "embedded/deno.exe.gz"
